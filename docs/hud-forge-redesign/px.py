def text(cv,t,x,y,c='#ffffff',sh=True,f=FONT):
    if isinstance(c,str): c=hx(c)
    sc=(c[0]//4,c[1]//4,c[2]//4,255)
    for pas in ((1,sc),(0,c)) if sh else ((0,c),):
        o,col=pas; cx=x
