from PIL import Image, ImageDraw
W,H=480,270
def hx(c,a=255):
    c=c.lstrip('#'); return (int(c[0:2],16),int(c[2:4],16),int(c[4:6],16),a)
class Cv:
    def __init__(s,w=W,h=H): s.im=Image.new('RGBA',(w,h),(0,0,0,0)); s.p=s.im.load(); s.w=w; s.h=h
    def px(s,x,y,c):
        if 0<=x<s.w and 0<=y<s.h:
            if isinstance(c,str): c=hx(c)
            if len(c)==4 and c[3]<255:
                b=s.p[x,y]; a=c[3]/255
                if b[3]==0: s.p[x,y]=c; return
                s.p[x,y]=(int(c[0]*a+b[0]*(1-a)),int(c[1]*a+b[1]*(1-a)),int(c[2]*a+b[2]*(1-a)),max(b[3],c[3]))
            else: s.p[x,y]=c if len(c)==4 else c+(255,)
    def rect(s,x,y,w,h,c):
        for j in range(y,y+h):
            for i in range(x,x+w): s.px(i,j,c)
    def hline(s,x,y,w,c): s.rect(x,y,w,1,c)
    def vline(s,x,y,h,c): s.rect(x,y,1,h,c)
    def bevel(s,x,y,w,h,R,inset=False,rim=1):
        # R ramp [o,d2,d,b,l,w]
        s.rect(x,y,w,h,R[0])
        s.rect(x+1,y+1,w-2,h-2,R[3])
        lt,dk=(R[4],R[2]) if not inset else (R[1],R[4])
        for k in range(rim):
            s.hline(x+1+k,y+1+k,w-2-2*k,lt); s.vline(x+1+k,y+1+k,h-2-2*k,lt)
            s.hline(x+1+k,y+h-2-k,w-2-2*k,dk); s.vline(x+w-2-k,y+1+k,h-2-2*k,dk)
        if not inset: s.px(x+1,y+1,R[5])
    def sprite(s,rows,x,y,R,extra=None):
        m={'o':R[0],'d':R[2],'b':R[3],'l':R[4],'w':R[5]}
        if extra: m.update(extra)
        for j,row in enumerate(rows):
            for i,ch in enumerate(row):
                if ch in m: s.px(x+i,y+j,m[ch])
    def blit(s,o,x=0,y=0):
        s.im.alpha_composite(o.im,(x,y)); s.p=s.im.load()
def shadow(cv,dx=1,dy=1,col=(0,0,0,110)):
    out=Cv(cv.w,cv.h)
    a=cv.im.split()[3]
    sh=Image.new('RGBA',(cv.w,cv.h),col); m=Image.new('L',(cv.w,cv.h),0); m.paste(a,(dx,dy))
    out.im.paste(sh,(0,0),m); out.p=out.im.load(); out.blit(cv); return out

